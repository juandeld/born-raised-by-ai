import type { ColorearLang } from "@lumen/config";
import type { OutboundMessage } from "@lumen/calls";

export interface MailVars {
  names: string;
  price: string;
  statusLink: string;
  deliveryLink?: string;
  refundLink: string;
  deleteDate: string;
  holder: string;
  privacyEmail: string;
  supportEmail: string;
  brand: string;
  notes?: string[];
}

type Kind = "receipt" | "delivery" | "refund";
type Tpl = (v: MailVars) => { subject: string; text: string };

const T: Record<Kind, Record<ColorearLang, Tpl>> = {
  receipt: {
    es: (v) => ({
      subject: `Recibo de su compra y datos de las fotos en ${v.brand}`,
      text: `Gracias por su compra. Este correo confirma el cobro de ${v.price} y repite lo que usted autorizó.\n\nRecibimos las fotos que subió y los nombres (${v.names}). Los usamos solo para crear su libro para colorear. Las fotos se envían a un proveedor externo de generación de imágenes, sin los nombres y solo para crear los dibujos (el detalle de proveedores está en nuestra política de privacidad). Las fotos se borran en cuanto los personajes están listos, siempre antes de 24 horas. No las vendemos, no reconocemos personas y no entrenamos modelos con ellas. El libro y los datos del pedido se borran el ${v.deleteDate}. Los dibujos y la historia los genera inteligencia artificial.\n\nSiga el avance de su libro aquí: ${v.statusLink}\nPara pedir reembolso (hasta 7 días después de la entrega): ${v.refundLink}\nSi usted no hizo esta compra, responda a este correo y la cancelamos y reembolsamos de inmediato.\n\n${v.holder} · ${v.privacyEmail}`,
    }),
    en: (v) => ({
      subject: `Your receipt and your photos at ${v.brand}`,
      text: `Thank you for your purchase. This email confirms the charge of ${v.price} and repeats what you authorized.\n\nWe received the photos you uploaded and the names (${v.names}). We use them only to create your coloring book. Photos go to an external image-generation provider, without the names and only to create the drawings (providers are listed in our privacy policy), and are deleted as soon as the characters are ready, always within 24 hours. We do not sell them, identify people or train models with them. The book and the order data are deleted on ${v.deleteDate}. The drawings and the story are generated by artificial intelligence.\n\nFollow your book's progress here: ${v.statusLink}\nTo request a refund (up to 7 days after delivery): ${v.refundLink}\nIf you did not make this purchase, reply to this email and we will cancel and refund it immediately.\n\n${v.holder} · ${v.privacyEmail}`,
    }),
  },
  delivery: {
    es: (v) => ({
      subject: `Su libro para colorear de ${v.names} ya está listo`,
      text: `¡Listo! Descargue e imprima su libro aquí: ${v.deliveryLink}\n\nEs un PDF de 24 páginas, listo para imprimir en casa (Carta o A4, escala 100 %). ${v.notes?.length ? `\nNota: ${v.notes.join(" ")}\n` : ""}\nEl enlace funciona hasta el ${v.deleteDate}; después el libro se borra automáticamente. Descárguelo antes.\nSi algo no le gustó, puede pedir el reembolso completo desde ese enlace.\n\n${v.brand} · ${v.supportEmail}`,
    }),
    en: (v) => ({
      subject: `Your coloring book for ${v.names} is ready`,
      text: `All done! Download and print your book here: ${v.deliveryLink}\n\nIt is a 24-page PDF, ready to print at home (Letter or A4, 100% scale). ${v.notes?.length ? `\nNote: ${v.notes.join(" ")}\n` : ""}\nThe link works until ${v.deleteDate}; after that the book is deleted automatically. Please download it before then.\nIf anything was not right, you can ask for a full refund from that link.\n\n${v.brand} · ${v.supportEmail}`,
    }),
  },
  refund: {
    es: (v) => ({
      subject: `Su reembolso de ${v.price}`,
      text: `Su reembolso de ${v.price} fue iniciado. Puede tardar unos días en aparecer según su banco. Borramos las fotos y el libro. Si necesita algo más, responda a este correo.\n\n${v.brand} · ${v.supportEmail}`,
    }),
    en: (v) => ({
      subject: `Your refund of ${v.price}`,
      text: `Your refund of ${v.price} has been started. It may take a few days to appear depending on your bank. We deleted the photos and the book. If you need anything else, reply to this email.\n\n${v.brand} · ${v.supportEmail}`,
    }),
  },
};

export function composeColorearMessage(kind: Kind, lang: ColorearLang, to: string, vars: MailVars): OutboundMessage {
  const { subject, text } = T[kind][lang](vars);
  return { kind: kind === "receipt" ? "receipt" : kind === "delivery" ? "delivery" : "refund", to, subject, text };
}
