export function renderColorearAviso(lang: Language, vars: Record<string, string>, opts: { gb?: boolean } = {}): ColorearAviso {
  const a = COLOREAR_AVISO[lang];
  const sections = a.sections.map((s) => ({ heading: s.heading, body: fill(s.body, vars) }));
  if (opts.gb && lang === "en") {
    const i = sections.findIndex((s) => s.heading === "Your rights:");
    if (i >= 0) sections[i] = { ...sections[i]!, body: `${sections[i]!.body} You may also complain to the Information Commissioner's Office.` };
  }
  return { id: a.id, title: a.title, intro: fill(a.intro, vars), sections, privacyLink: fill(a.privacyLink, vars) };
}
